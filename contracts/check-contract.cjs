const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
if (!process.argv[2]) throw new Error('Supply a path to an existing Ajv 6 module');
const Ajv = require(process.argv[2]);
const schema = JSON.parse(fs.readFileSync(path.join(__dirname, 'character-context.schema.json'), 'utf8'));
const fixture = JSON.parse(fs.readFileSync(path.join(__dirname, 'examples/unavailable.json'), 'utf8'));
const ajv = new Ajv({ allErrors: true, unknownFormats: 'fail' });
assert(ajv.validateSchema(schema), JSON.stringify(ajv.errors));
const validate = ajv.compile(schema);
const questSchema = JSON.parse(fs.readFileSync(path.join(__dirname, 'quest-pilot-capture.schema.json'), 'utf8'));
assert(ajv.validateSchema(questSchema), JSON.stringify(ajv.errors));
ajv.compile(questSchema);
const questV2 = JSON.parse(fs.readFileSync(path.join(__dirname, 'quest-pilot-capture-v2.schema.json'), 'utf8'));
assert(ajv.validateSchema(questV2), JSON.stringify(ajv.errors));
ajv.compile(questV2);
const questV3 = JSON.parse(fs.readFileSync(path.join(__dirname, 'quest-pilot-capture-v3.schema.json'), 'utf8'));
assert(ajv.validateSchema(questV3), JSON.stringify(ajv.errors));
ajv.compile(questV3);
const questV4 = JSON.parse(fs.readFileSync(path.join(__dirname, 'quest-pilot-capture-v4.schema.json'), 'utf8'));
assert(ajv.validateSchema(questV4), JSON.stringify(ajv.errors));
ajv.compile(questV4);
assert(validate(fixture), JSON.stringify(validate.errors));
const reject = (mutate) => {
  const value = JSON.parse(JSON.stringify(fixture));
  mutate(value);
  assert.equal(validate(value), false, 'Invalid context was accepted');
};
reject(v => { v.game = 'wow-retail'; });
reject(v => { v.provenance.freshness = 'live'; });
reject(v => { v.provenance.retrievedAt = 'not-a-date'; });
reject(v => { v.summary = { status: 'unavailable', data: { level: 60 } }; });
reject(v => { v.equipment = { status: 'planned' }; });
reject(v => { v.command = 'arbitrary-action'; });
reject(v => { v.talents = { status: 'observed', data: { configuration: { status: 'unavailable' }, selected: [{ id: 1, rank: 0 }] } }; });
reject(v => { v.equipment = { status: 'partial', data: { slots: [{ slot: 20, item: { status: 'unavailable' }, itemLink: { status: 'unavailable' }, statsStatus: 'unknown', effectsStatus: 'unknown' }] } }; });
console.log('Character and quest capture schemas compiled; synthetic unavailable fixture accepted; 8 invalid contexts rejected.');
